// LAZY LOADERS of Forge (design §6.2, §6.3, §22.3). Signatures frozen in Phase 0; these are the real bodies
// (forge/p-plataforma). Nothing here builds a URL or a path from free text: every book and bank is looked up by its
// code in the generated indexes (books-publish.mjs), and every route by its slug in a fixed table.

export type EnsureResult =
  | { ok: true; refreshed: boolean }
  | { ok: false; reason: "desconocido" | "no-descargado" | "despues-del-intento" | "formato" };

export type EnsureBankResult =
  | { ok: true; refreshed: boolean; pendientes: string[] }
  | { ok: false; reason: "desconocido" | "no-descargado" | "invalido"; details?: string[] };

