/** Route data of one of the 19 paths; null for an unknown slug or a chunk that did not load. */
export async function loadForgeRoute(slug: string): Promise<ForgeRouteData | null> {
  if (!Object.prototype.hasOwnProperty.call(ROUTE_LOADERS, slug)) return null;
  try {
    const m = await ROUTE_LOADERS[slug as ForgePathSlug]();
    const data = (m.default ?? m) as ForgeRouteData;
    return data && data.v === 1 && data.slug === slug ? data : null;
  } catch {
    return null;
  }
}

interface BookIndexEntry {
  file: string;
  sha10: string;
  bytes: number;
  /** null when the book declares no reading time (H2 of design poblar) */
  minutes: number | null;
  title: string;
}
const BOOK_FILE = /^[a-z0-9-]+\.[0-9a-f]{10}\.md$/;
const CODE = /^[A-Z][A-Z0-9]{0,3}-\d{2}$/;

let bookIndexP: Promise<Record<string, BookIndexEntry>> | null = null;
/** book-index.json (generated by books-publish.mjs), memoized; an empty index if the chunk does not load. */
export function forgeBookIndex(): Promise<Record<string, BookIndexEntry>> {
  bookIndexP ??= import("./data/book-index.json")
    .then((m) => ((m as { default?: unknown }).default ?? m) as Record<string, BookIndexEntry>)
    .catch(() => {
      bookIndexP = null;
      return {};
    });
  return bookIndexP;
}

let bankIndexP: Promise<Record<string, string>> | null = null;
function bankIndex(): Promise<Record<string, string>> {
  bankIndexP ??= import("./data/bank-index.json")
    .then((m) => ((m as { default?: unknown }).default ?? m) as Record<string, string>)
    .catch(() => {
      bankIndexP = null;
      return {};
    });
  return bankIndexP;
}

/** sha256[:10] of the UTF-8 bytes (the same fingerprint books-publish.mjs writes). */
export async function sha10(text: string): Promise<string> {
  const buf = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(text));
  return Array.from(new Uint8Array(buf), (b) => b.toString(16).padStart(2, "0")).join("").slice(0, 10);
}

/** The book .md of a cell from public/forge/books/v1, looked up in the index (never a URL built from free text). */
export async function loadForgeBookMd(code: string): Promise<string | null> {
  if (!CODE.test(code)) return null;
  const entry = (await forgeBookIndex())[code];
  if (!entry || !BOOK_FILE.test(entry.file)) return null;
  const res = await fetch(`/forge/books/v1/${entry.file}`).catch(() => null); // CacheFirst in the SW (§6.6)
  if (!res || !res.ok) return null;
  return res.text();
}

/** A diagnostic's reading opens only after its first observed pass (§8.6): some evidence recorded on that cell. */
function hasFirstPassObservation(readModel: ReadModel, code: string): boolean {
  const id = forgeCellId(code);
  return readModel.evidence.some((e) => e.moduleId === id);
}

/** Materialize (or refresh) the book of a cell in arcanum-books (§6.2). */
export async function ensureForgeBook(code: string, readModel: ReadModel): Promise<EnsureResult> {
  if (!CODE.test(code)) return { ok: false, reason: "desconocido" };
  const entry = (await forgeBookIndex())[code];
  if (!entry) return { ok: false, reason: "desconocido" };
  if (isDiagnosticCode(code) && !hasFirstPassObservation(readModel, code)) return { ok: false, reason: "despues-del-intento" };
  const row = await getBookForModule(forgeCellId(code));
  if (row && (row.source === "import" || (await sha10(row.md)) === entry.sha10)) return { ok: true, refreshed: false };
  const md = await loadForgeBookMd(code);
  if (md === null) return row ? { ok: true, refreshed: false } : { ok: false, reason: "no-descargado" };
  if ((await sha10(md)) !== entry.sha10 || parseBook(md) === null) {
    console.error(`[forge] el libro ${code} descargado no coincide con el índice`);
    return row ? { ok: true, refreshed: false } : { ok: false, reason: "formato" };
  }
  await seedBooks([md]);
  // the URL carries the sha10: a corrected book is another file, so the old ones go (design poblar §6.9)
  await pruneBookVersions(code, entry.file);
  return { ok: true, refreshed: true };
}

/** Where a bank's .md comes from: a lazy chunk per bank under content/forge/exercises (asset/source → text).
 *  The context is content/ filtered to forge/exercises/*.md, so the books of content/books never enter it and an
 *  absent folder is an empty context, not a build error. Tests replace `load`. */
export const forgeBankSource = {
  load: async (code: string): Promise<string> => {
    const rel = `forge/exercises/${code.toLowerCase()}.md`;
    const m = (await import(
      /* webpackInclude: /forge[\\/]exercises[\\/][a-z0-9-]+\.md$/ */
      /* webpackChunkName: "forge-bank-[request]" */
      `../../content/${rel}`
    )) as { default?: unknown };
    return String(m.default ?? m);
  },
};

/** Ingest (or refresh) the bank of a cell with saveExerciseBank(md, { source: "seed" }) (§6.3). */
export async function ensureForgeBank(code: string): Promise<EnsureBankResult> {
  if (!CODE.test(code)) return { ok: false, reason: "desconocido" };
  const expected = (await bankIndex())[code];
  if (!expected) return { ok: false, reason: "desconocido" };
  let md: string;
  try {
    md = await forgeBankSource.load(code);
  } catch {
    return { ok: false, reason: "no-descargado" };
  }
  const rows = await getBanksForModule(forgeCellId(code));
  const imported = rows.find((r) => r.source === "import");
  if (imported) return { ok: true, refreshed: false, pendientes: imported.pendientes ?? [] };
  const seeded = rows.find((r) => r.source === "seed");
  // save when there is no row, when the packaged md differs (a deploy that fixes a bank), or when the row still
  // has pending items (a deploy that replaces a stub check re-validates)
  if (seeded && seeded.md === md && (seeded.pendientes ?? []).length === 0) return { ok: true, refreshed: false, pendientes: [] };
  const saved = await saveExerciseBank(md, { source: "seed" });
  if (!saved.ok) {
    if (saved.missingCheck) return { ok: false, reason: "no-descargado", details: saved.details };
    return { ok: false, reason: "invalido", details: saved.details ?? [saved.error] };
  }
  return { ok: true, refreshed: true, pendientes: saved.bank.pendientes };
}

/** Items of the cell's bank and the ids of its pending items (§6.3); null when the bank is not on this device. */
export async function loadForgeBankItems(code: string): Promise<{ items: ForgeBankItem[]; pendientes: string[] } | null> {
  if (!CODE.test(code)) return null;
  const rows = await getBanksForModule(forgeCellId(code));
  const row = rows.find((r) => r.source === "import") ?? rows.find((r) => r.source === "seed");
  if (!row) return null;
  const parsed = parseExercisesMd(row.md);
  const items = (parsed?.exercises ?? []).filter((e): e is ForgeBankItem => isForgeType(String((e as { type?: unknown }).type ?? "")));
  return { items, pendientes: row.pendientes ?? [] };
}
